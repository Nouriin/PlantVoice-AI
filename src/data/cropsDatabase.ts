export const CROP_CATEGORIES = [
  "All",
  "Cereals & Grains",
  "Vegetables",
  "Fruits",
  "Pulses & Legumes",
  "Cash & Commercial",
  "Spices & Plantation",
  "Oilseeds & Others"
] as const;

export function searchCrops(query: string, category: string = "All"): CropData[] {
  const q = query.trim().toLowerCase();
  return CROPS_DATABASE.filter((crop) => {
    const matchesCat = category === "All" || crop.category === category;
    if (!matchesCat) return false;
    if (!q) return true;
    return (
      crop.name.toLowerCase().includes(q) ||
      crop.scientificName.toLowerCase().includes(q) ||
      crop.category.toLowerCase().includes(q) ||
      crop.vulnerabilities.some(v => v.toLowerCase().includes(q)) ||
      crop.commonDiseases.some(d => d.toLowerCase().includes(q))
    );
  });
}
